    /// P1: each fail diagnostic names the promise and the consequence, never
    /// the step, a planted value or a threshold. Fail-without mutant: put
    /// the missing note's name into the consequence.
    #[test]
    fn diagnostic_hides_how() {
        let fx = Fx::new("hides");
        let binding = notes_binding();
        for variant in ["breaks", "refuses"] {
            let e = fx.variant(variant);
            let public = e.record.public();
            assert_eq!(public.decision, Decision::Fail);
            assert!(!public.diagnostics.is_empty());
            let text = serde_json::to_string(&public).unwrap();
            let secrets = e.record.body.planted.secrets();
            // Non-vacuous: the sealed record does carry the planted values.
            let full = serde_json::to_string(&e.record).unwrap();
            assert!(secrets.iter().all(|s| full.contains(s.as_str())));
            for s in &secrets {
                assert!(
                    !text.contains(s.as_str()),
                    "{variant}: a diagnostic names a planted value"
                );
            }
            for c in &e.record.body.checks {
                assert!(
                    !text.contains(&format!("\"{}\"", c.id)),
                    "{variant}: names a step"
                );
            }
            assert!(!text.contains("check-") && !text.to_lowercase().contains("step"));
            for d in &public.diagnostics {
                let promise = d.promise_text.as_deref().expect("a promise is named");
                assert!(
                    binding.probe_for(promise).is_some(),
                    "the owner's words: {promise}"
                );
                assert!(!d.consequence.is_empty());
                assert!(
                    !d.consequence.bytes().any(|b| b.is_ascii_digit()),
                    "a consequence carries a number: {}",
                    d.consequence
                );
                assert!(!d.consequence.contains("byte"));
            }
        }
    }

