    /// P1: the correct variant, built from source at its commit and observed
    /// only at its boundary, passes the approved plan; the server accepts
    /// the verdict. Fail-without mutant: compare the interrupted-save
    /// `get` output against the card's example body instead of the planted
    /// body.
    #[test]
    fn keeps_passes() {
        let fx = Fx::new("keeps");
        let e = fx.variant("keeps");
        let b = &e.record.body;
        assert!(!b.checks.is_empty());
        assert!(
            b.checks.iter().all(|c| c.probe.is_some()),
            "every check of the plan is bound to a boundary probe: {:?}",
            b.checks
        );
        assert!(
            b.checks
                .iter()
                .any(|c| c.probe == Some(Probe::InterruptedSave))
        );
        assert_eq!(e.record.decision(), Decision::Pass, "{:#?}", b.decided);
        assert!(b.decided.diagnostics.is_empty());
        assert_eq!(server_decision(&e), "pass");
        // Observed only at the boundary: process runs and files.
        assert!(
            b.observations
                .iter()
                .any(|o| matches!(o.observed, Observed::Process { .. }))
        );
        assert!(b.confinement.writes_confined, "{:?}", b.confinement);
        assert!(b.confinement.runs > 1);
    }

