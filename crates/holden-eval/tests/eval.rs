    /// P2: the planted values come from the server's `reveal_params` for
    /// this run, and from nothing else; a forged reveal, a reveal for
    /// another commit, and a run the server never opened are all refused.
    /// Fail-without mutant: let the evaluator compute the parameters locally.
    #[test]
    fn params_must_come_from_server() {
        let fx = Fx::new("params");
        let keeps = fx.commit("keeps");
        let breaks = fx.commit("breaks");
        let c = fx.client();
        let req = fx.request(&keeps, &keeps);
        let run = fx.evaluator.begin(&c, &req).unwrap();
        let e = fx.evaluator.evaluate_run(&c, &req, &run).unwrap();
        keep_record("params", &e.record);
        assert_eq!(server_decision(&e), "pass");
        // The verdict closed the run; the audit gives the server's draw.
        let audit = c.call("audit_reveal", json!({ "run_id": run })).unwrap();
        let p = &e.record.body.reveal.params;
        assert_eq!(audit["params"]["bytes"].as_str().unwrap(), p.bytes);
        assert_eq!(
            audit["output"].as_str().unwrap(),
            e.record.body.reveal.output
        );
        let bytes: [u8; 32] = hex::decode(&p.bytes).unwrap().try_into().unwrap();
        assert_eq!(e.record.body.planted, Planted::derive(&bytes));

        // A reveal is accepted only for its own plan, commit and key, and
        // only with the parameters its proof derives.
        let run2 = fx.evaluator.begin(&c, &req).unwrap();
        let body = c.call("reveal_params", json!({ "run_id": run2 })).unwrap();
        let published = c.call("brief", json!({})).unwrap()["epoch_public_key"]
            .as_str()
            .unwrap()
            .to_owned();
        assert!(ServerReveal::from_reveal_body(&body, &published, &fx.plan_commit, &keeps).is_ok());
        assert_eq!(
            ServerReveal::from_reveal_body(&body, &published, &fx.plan_commit, &breaks),
            Err(ParamRefusal::OtherCommit)
        );
        assert_eq!(
            ServerReveal::from_reveal_body(&body, &published, &fx.legacy_commit, &keeps),
            Err(ParamRefusal::OtherPlan)
        );
        let mut forged = body.clone();
        let mut b = hex::decode(forged["params"]["bytes"].as_str().unwrap()).unwrap();
        b[0] ^= 1;
        forged["params"]["bytes"] = Value::String(hex::encode(b));
        assert_eq!(
            ServerReveal::from_reveal_body(&forged, &published, &fx.plan_commit, &keeps),
            Err(ParamRefusal::ProofRefused)
        );

        // The evaluator refuses to plant from a run opened for another commit.
        let other = fx.request(&breaks, &keeps);
        assert_eq!(
            fx.evaluator.evaluate_run(&c, &other, &run2).unwrap_err(),
            EvalError::Params(ParamRefusal::OtherCommit)
        );
        // And from a run the server never opened.
        let err = fx
            .evaluator
            .evaluate_run(&c, &req, &hex::encode([7u8; 32]))
            .unwrap_err();
        assert!(
            matches!(&err, EvalError::Server(r) if r.code == "unknown_run"),
            "{err:?}"
        );
    }

    /// P2: the same plan against two different evaluated commits plants
    /// different values, each bound by the VRF proof to its own commit.
    /// Fail-without mutant: derive the planted values from the plan commit
    /// alone.
    #[test]
    fn planted_values_differ_per_commit() {
        let fx = Fx::new("percommit");
        let a = fx.variant("keeps");
        let b = fx.variant("reconfig");
        assert_ne!(
            a.record.body.evaluated_commit,
            b.record.body.evaluated_commit
        );
        assert_eq!(a.record.body.plan_commit, b.record.body.plan_commit);
        assert_ne!(a.record.body.planted, b.record.body.planted);
        let names = |e: &Evaluation| -> BTreeSet<String> {
            e.record
                .body
                .planted
                .notes
                .iter()
                .map(|n| n.name.clone())
                .collect()
        };
        assert!(names(&a).is_disjoint(&names(&b)));
        for e in [&a, &b] {
            let r = &e.record.body.reveal;
            assert_eq!(r.evaluated_commit, e.record.body.evaluated_commit);
            r.verify().unwrap();
            assert_eq!(server_decision(e), "pass");
        }
    }

