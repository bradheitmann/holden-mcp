    /// An approved plan: generated by holden-gen from the synthetic
    /// planning document, for its promise `k` (0: "A saved note is never
    /// lost …"), in the first candidate cognition, approved by the owner key.
    fn generated_plan(store: &FileKeyStore, k: usize) -> GenPlan {
        let doctrine = Doctrine::holden();
        let doc = PlanningDocument::read(&synthetic().join("PLANNING.md"), "PLANNING.md").unwrap();
        let promises = extract_promises(&doc).unwrap();
        let owner = OwnerKey::load(store, &KeyName::new("owner").unwrap()).unwrap();
        let draw_key = DrawKey::load(store, &KeyName::new("draw").unwrap()).unwrap();
        let p = &promises[k];
        let c = candidates(&doctrine, p, None).into_iter().next().unwrap();
        let approval = Approval::sign(&owner, &c);
        let hosted =
            HostableCognition::admit(&doc, p, &c, Some(&approval), &owner.public()).unwrap();
        let corpus = DrawCorpus::load(&synthetic().join("lens")).unwrap();
        let inputs = holden_gen::DrawInputs {
            promise: hosted.promise().id,
            cognition: hosted.cognition().id,
            epoch: 0,
        };
        let d = draw_lens(&draw_key, &corpus, &inputs).unwrap();
        let approved: Vec<_> = promises.iter().collect();
        generate(&doctrine, &hosted, &approved, &corpus, &d)
            .unwrap()
            .plan
    }

    /// How many promises the synthetic planning document holds.
    const PROMISES: usize = 4;

    /// One test's world: keys, a sealed generated plan for each promise
    /// (and a slice-1 plan) registered with a real server on a real socket,
    /// a fixture repository and an evaluator.
    struct Fx {
        root: PathBuf,
        _rt: tokio::runtime::Runtime,
        listener: Listener,
        socket: PathBuf,
        plan: GenPlan,
        plan_commit: PlanCommit,
        /// The plan of every promise, in planning-document order (the first
        /// is `plan`).
        plans: Vec<(GenPlan, PlanCommit)>,
        legacy_commit: PlanCommit,
        repo: FixtureRepo,
        evaluator: Evaluator,
        evaluator_public: EvaluatorPublicKey,
    }

    impl Fx {
        fn new(tag: &str) -> Self {
            let root = std::env::temp_dir().join(format!("hm4-{tag}-{}", std::process::id()));
            let _ = fs::remove_dir_all(&root);
            DirBuilder::new()
                .recursive(true)
                .mode(0o700)
                .create(&root)
                .unwrap();
            let store = FileKeyStore::open(root.join("k")).unwrap();
            for (name, bytes) in [
                ("epoch", EPOCH_SEED),
                ("seal", SEAL_KEY),
                ("owner", OWNER_KEY),
                ("draw", DRAW_KEY),
                ("evaluator", EVALUATOR_KEY),
            ] {
                store
                    .put(
                        &KeyName::new(name).unwrap(),
                        &KeyMaterial::from_bytes(bytes),
                    )
                    .unwrap();
            }
            let plan = generated_plan(&store, 0);
            let seal_key = SealKey::new(store.get(&KeyName::new("seal").unwrap()).unwrap());
            let (sealed, card) = seal_plan(&seal_key, &plan).unwrap();
            let plans = root.join("p");
            fs::create_dir_all(&plans).unwrap();
            fs::write(
                plans.join("generated.sealed.json"),
                serde_json::to_vec(&SealedPlanFile::from_sealed(&sealed)).unwrap(),
            )
            .unwrap();
            let mut all = vec![(plan.clone(), plan_commit(&sealed))];
            for k in 1..PROMISES {
                let p = generated_plan(&store, k);
                let (s, _) = seal_plan(&seal_key, &p).unwrap();
                fs::write(
                    plans.join(format!("generated-{k}.sealed.json")),
                    serde_json::to_vec(&SealedPlanFile::from_sealed(&s)).unwrap(),
                )
                .unwrap();
                all.push((p, plan_commit(&s)));
            }
            let legacy = holden_seal::seal::seal(
                &seal_key,
                &Plan {
                    id: PlanId(seeded(9)),
                    cognition: "slice-1 plan".to_owned(),
                    steps: vec![PlanStep {
                        action: "a".to_owned(),
                        expect: "b".to_owned(),
                    }],
                },
            )
            .unwrap();
            fs::write(
                plans.join("legacy.sealed.json"),
                serde_json::to_vec(&SealedPlanFile::from_sealed(&legacy)).unwrap(),
            )
            .unwrap();
            let legacy_commit = plan_commit(&legacy);
            let plan_commit = plan_commit(&sealed);
            assert_eq!(card.plan_commit, hex::encode(plan_commit.0));
            let evaluator_key =
                EvaluatorKey::load(&store, &KeyName::new("evaluator").unwrap()).unwrap();
            let evaluator_public = evaluator_key.public();
            let config = json!({
                "socket_dir": root.join("s"),
                "key_dir": root.join("k"),
                "epoch_key": "epoch",
                "seal_key": "seal",
                "plans_dir": plans,
                "run_window_ms": WINDOW_MS,
                "roles": [{ "uid": holden_seal::keystore::current_uid(), "role": "evaluator" }],
                "verdict_key": hex::encode(evaluator_public.0),
            });
            let config = Arc::new(ServerConfig::from_json(&config.to_string()).unwrap());
            let rt = tokio::runtime::Builder::new_multi_thread()
                .worker_threads(2)
                .enable_all()
                .build()
                .unwrap();
            let core = Arc::new(Core::open(&config, Clock::System, Log::capture()).unwrap());
            let listener = {
                let _guard = rt.enter();
                serve_socket(core, Arc::clone(&config)).unwrap()
            };
            let repo = FixtureRepo::create(
                &crate_dir().join("../..").join(NOTES_FIXTURE),
                &root.join("repo"),
            )
            .unwrap();
            let evaluator = Evaluator::new(
                evaluator_key,
                Toolchain {
                    cargo: PathBuf::from(env!("CARGO")),
                },
                PathBuf::from(env!("CARGO_BIN_EXE_holden-confine")),
                root.join("worlds"),
                notes_binding(),
            );
            Self {
                socket: config.socket_path(),
                root,
                _rt: rt,
                listener,
                plan,
                plan_commit,
                plans: all,
                legacy_commit,
                repo,
                evaluator,
                evaluator_public,
            }
        }

        fn client(&self) -> McpClient {
            McpClient::connect(&self.socket).unwrap()
        }

        fn commit(&self, variant: &str) -> String {
            self.repo.commit(variant).unwrap()
        }

        fn request<'a>(&'a self, commit: &'a str, baseline: &'a str) -> EvalRequest<'a> {
            EvalRequest {
                repo: &self.repo.path,
                plan: &self.plan,
                plan_commit: self.plan_commit,
                evaluated_commit: commit,
                baseline_commit: baseline,
            }
        }

        /// Evaluate `commit` end to end over a fresh client.
        fn run_commit(&self, commit: &str, name: &str) -> Evaluation {
            let base = self.commit("keeps");
            let c = self.client();
            let e = self
                .evaluator
                .evaluate(&c, &self.request(commit, &base))
                .unwrap();
            keep_record(name, &e.record);
            e
        }

        /// Evaluate the fixture variant `variant` end to end.
        fn variant(&self, variant: &str) -> Evaluation {
            let commit = self.commit(variant);
            self.run_commit(&commit, variant)
        }

        /// Evaluate the fixture variant `variant` end to end under the plan
        /// of promise `k`.
        fn plan_variant(&self, k: usize, variant: &str) -> Evaluation {
            let (plan, plan_commit) = &self.plans[k];
            let commit = self.commit(variant);
            let base = self.commit("keeps");
            let req = EvalRequest {
                repo: &self.repo.path,
                plan,
                plan_commit: *plan_commit,
                evaluated_commit: &commit,
                baseline_commit: &base,
            };
            let e = self.evaluator.evaluate(&self.client(), &req).unwrap();
            keep_record(&format!("plan{k}-{variant}"), &e.record);
            e
        }
    }

    impl Drop for Fx {
        fn drop(&mut self) {
            self.listener.stop();
            let _ = fs::remove_dir_all(&self.root);
        }
    }

    /// Write `record` to `HOLDEN_EVAL_RECORD_DIR`, when set (reopen).
    fn keep_record(name: &str, record: &VerdictRecord) {
        if let Some(dir) = std::env::var_os("HOLDEN_EVAL_RECORD_DIR") {
            let dir = PathBuf::from(dir);
            fs::create_dir_all(&dir).unwrap();
            let file = dir.join(format!(
                "{name}-{}-{}.json",
                std::process::id(),
                &record.body.world_id[..8]
            ));
            fs::write(file, serde_json::to_vec_pretty(record).unwrap()).unwrap();
        }
    }

    fn server_decision(e: &Evaluation) -> String {
        let ok = e.server.as_ref().expect("the server accepts the verdict");
        ok["decision"].as_str().unwrap().to_owned()
    }

    fn process<'a>(obs: &'a [Observation], probe: Probe, label: &str) -> &'a Observed {
        &obs.iter()
            .find(|o| o.probe == Some(probe) && o.label == label)
            .unwrap_or_else(|| panic!("no {label} observation for {probe:?}"))
            .observed
    }

    fn stdout_lines(o: &Observed) -> Vec<String> {
        match o {
            Observed::Process { stdout, .. } => stdout.text().lines().map(str::to_owned).collect(),
            Observed::File { .. } => panic!("not a process"),
        }
    }

    fn stderr_text(o: &Observed) -> String {
        match o {
            Observed::Process { stderr, .. } => stderr.text(),
            Observed::File { .. } => panic!("not a process"),
        }
    }

