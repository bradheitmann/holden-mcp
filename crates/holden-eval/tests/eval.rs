    /// The index of the plan whose promise is bound to `probe`.
    fn plan_of(fx: &Fx, probe: Probe) -> usize {
        let binding = notes_binding();
        fx.plans
            .iter()
            .position(|(p, _)| {
                let promise = p.provenance.promise.to_hex();
                binding
                    .bind(p)
                    .iter()
                    .any(|c| c.promise == promise && c.probe == Some(probe))
            })
            .unwrap_or_else(|| panic!("no plan's own promise is bound to {probe:?}"))
    }

    /// slice-5 P6(a): a product that keeps every promise at its boundary but
    /// attempts to write outside its world on its refusal paths (`sneaks`)
    /// never passes: the verdict fails with the typed reason
    /// `confinement_violation`, and with no other reason, while the correct
    /// product passes the same plans. Where the backend cannot observe an
    /// attempt (Linux Landlock denies silently), the verdict records the
    /// typed limitation instead, which caps authority at `recommend`
    /// (holden-ledger `limitation_caps_authority`).
    /// Fail-without mutant: let a confinement violation leave the decision
    /// unchanged (drop the rule in `rules::decide`).
    #[test]
    fn confinement_violation_fails_verdict() {
        let fx = Fx::new("violation");
        for probe in [Probe::DeleteAsksFirst, Probe::ExportFailureExplained] {
            let k = plan_of(&fx, probe);
            let good = fx.plan_variant(k, "keeps");
            assert_eq!(
                good.record.decision(),
                Decision::Pass,
                "{:#?}",
                good.record.body.decided
            );
            let e = fx.plan_variant(k, "sneaks");
            let b = &e.record.body;
            assert!(
                b.observations.iter().any(|o| o.probe == Some(probe)),
                "the {probe:?} probe ran"
            );
            assert!(
                !fx.evaluator.scratch().join("sneaked-out.txt").exists(),
                "the product wrote outside its world"
            );
            if b.confinement.product_violations_kill {
                assert_eq!(e.record.decision(), Decision::Fail, "{:#?}", b.decided);
                assert_eq!(
                    b.decided.reasons,
                    vec![FailReason::ConfinementViolation],
                    "only the violation fails it: every check held"
                );
                assert!(
                    b.decided
                        .results
                        .iter()
                        .all(|r| r.outcome == CheckOutcome::Held)
                );
                assert!(
                    b.decided
                        .diagnostics
                        .iter()
                        .any(|d| d.consequence == consequence::CONFINEMENT)
                );
                let public = e.record.public();
                assert!(public.reasons.contains(&FailReason::ConfinementViolation));
                assert_eq!(server_decision(&e), "fail");
                // The decision replays from the record alone.
                let replayed = replay(&e.record, Some(&fx.evaluator_public)).unwrap();
                assert_eq!(replayed.reasons, b.decided.reasons);
            } else {
                assert!(
                    b.confinement
                        .limitations
                        .contains(&Limitation::ViolationAttemptsNotObserved),
                    "{:?}",
                    b.confinement
                );
            }
        }
    }

    /// slice-7 P5: a product process cannot read the sealed side. The
    /// server's real sealed plan file is planted next to the world, where the
    /// `peeks` variant (which keeps every promise) tries to read it on every
    /// import. The read is refused: on macOS the product is killed at the
    /// attempt and the verdict fails with `confinement_violation`; on Linux
    /// Landlock refuses it. No byte of the sealed file reaches any
    /// observation, and no run carries `reads_not_confined`.
    /// Fail-without mutant: remove the read restriction (macOS: the
    /// `file-read*` rules of `confine/macos-product.sb`; Linux: the read
    /// rules `holden-confine` gives Landlock).
    #[test]
    fn sealed_read_is_denied() {
        let fx = Fx::new("peek");
        let sealed = fs::read(fx.root.join("p/generated.sealed.json")).unwrap();
        let file: SealedPlanFile = serde_json::from_slice(&sealed).unwrap();
        let marker = &file.ciphertext[..64];
        fs::create_dir_all(fx.evaluator.scratch()).unwrap();
        let planted = fx.evaluator.scratch().join("planted-sealed.json");
        fs::write(&planted, &sealed).unwrap();
        // Unconfined, the variant's relative path names the planted file.
        let probe_world = World::create(fx.evaluator.scratch()).unwrap();
        let unconfined = fs::read(probe_world.path("run").join("../../planted-sealed.json"));
        assert_eq!(unconfined.unwrap(), sealed, "the planted file is reachable");
        probe_world.remove();

        let e = fx.variant("peeks");
        let b = &e.record.body;
        assert!(
            !b.confinement
                .limitations
                .contains(&Limitation::ReadsNotConfined),
            "{:?}",
            b.confinement
        );
        let import = process(&b.observations, Probe::InterruptedSave, "import");
        if b.confinement.product_violations_kill {
            assert!(
                matches!(
                    import,
                    Observed::Process {
                        exit: Exit::Signal { signal: 9 },
                        ..
                    }
                ),
                "{import:?}"
            );
            assert!(
                b.decided
                    .reasons
                    .contains(&FailReason::ConfinementViolation),
                "{:?}",
                b.decided
            );
            assert_eq!(e.record.decision(), Decision::Fail);
        } else {
            assert!(
                stderr_text(import).contains("peek: denied"),
                "{}",
                stderr_text(import)
            );
        }
        for o in &b.observations {
            if let Observed::Process { stdout, stderr, .. } = &o.observed {
                for text in [stdout.text(), stderr.text()] {
                    assert!(!text.contains("peek: read"), "{}: {text}", o.id);
                    assert!(!text.contains(marker), "{}: sealed bytes observed", o.id);
                }
            }
        }
        let full = serde_json::to_string(&e.record).unwrap();
        assert!(!full.contains(marker), "the record holds sealed bytes");
        keep_record("peeks", &e.record);
    }

    /// slice-5 P6(b): the generated plans' list, export and delete probes
    /// (with the interrupted-save probe) each run end to end against the
    /// fixture product: every check of every promise's plan is bound to a
    /// probe; the correct product passes each plan with every probe its
    /// checks need observed; and the product that does nothing for a probe's
    /// promise fails that probe's plan with a check that did not hold.
    /// Fail-without mutant: bind only the interrupted-save promise in
    /// `notes_binding`.
    #[test]
    fn all_generated_probes_run() {
        let fx = Fx::new("probes");
        let binding = notes_binding();
        let mut ran = BTreeSet::new();
        for (k, (plan, _)) in fx.plans.iter().enumerate() {
            let checks = binding.bind(plan);
            assert!(
                checks.iter().all(|c| c.probe.is_some()),
                "plan {k}: an unbound check: {checks:?}"
            );
            let e = fx.plan_variant(k, "keeps");
            assert_eq!(
                e.record.decision(),
                Decision::Pass,
                "plan {k}: {:#?}",
                e.record.body.decided
            );
            for c in &checks {
                let p = c.probe.unwrap();
                assert!(
                    e.record
                        .body
                        .observations
                        .iter()
                        .any(|o| o.probe == Some(p)),
                    "plan {k}: probe {p:?} did not run"
                );
                ran.insert(p);
            }
        }
        assert_eq!(ran, Probe::ALL.into_iter().collect::<BTreeSet<_>>());
        for p in Probe::ALL {
            let k = plan_of(&fx, p);
            let e = fx.plan_variant(k, do_nothing_variant(p));
            let b = &e.record.body;
            assert_eq!(
                e.record.decision(),
                Decision::Fail,
                "{p:?}: {:#?}",
                b.decided
            );
            assert!(
                b.checks
                    .iter()
                    .zip(&b.decided.results)
                    .any(|(c, r)| c.probe == Some(p) && r.outcome != CheckOutcome::Held),
                "{p:?}: no check of the probe failed: {:#?}",
                b.decided
            );
        }
    }
