    /// `replay` and by the server's `verdict`. Fail-without mutant: skip the
    /// digest check in `replay`.
    #[test]
    fn tampered_record_is_refused() {
        let fx = Fx::new("tamper");
        let keeps = fx.commit("keeps");
        let c = fx.client();
        let req = fx.request(&keeps, &keeps);
        let run = fx.evaluator.begin(&c, &req).unwrap();
        let (record, _world) = fx.evaluator.prepare(&c, &req, &run).unwrap();
        let pinned = Some(&fx.evaluator_public);
        replay(&record, pinned).unwrap();

        let flip_stdout = |r: &mut VerdictRecord| {
            let o = r
                .body
                .observations
                .iter_mut()
                .find(|o| {
                    matches!(&o.observed, Observed::Process { stdout, .. } if !stdout.hex.is_empty())
                })
                .unwrap();
            if let Observed::Process { stdout, .. } = &mut o.observed {
                let mut b = hex::decode(&stdout.hex).unwrap();
                b[0] ^= 0x20;
                stdout.hex = hex::encode(b);
            }
        };
        // A changed observation breaks the signature.
        let mut t = record.clone();
        flip_stdout(&mut t);
        assert_eq!(replay(&t, pinned), Err(ReplayRefusal::BadSignature));
        // Even signed by the evaluator key itself, an observation that does
        // not match its recorded digest is refused.
        let mut t = record.clone();
        flip_stdout(&mut t);
        let own = EvaluatorKey::from_material(&KeyMaterial::from_bytes(EVALUATOR_KEY));
        let t = VerdictRecord::sign(t.body, &own);
        assert_eq!(replay(&t, pinned), Err(ReplayRefusal::DigestMismatch));
        // A changed observation with its digest recomputed: the signature.
        let mut t = record.clone();
        flip_stdout(&mut t);
        t.body.observation_digests = t
            .body
            .observations
            .iter()
            .map(Observation::digest)
            .collect();
        assert_eq!(replay(&t, pinned), Err(ReplayRefusal::BadSignature));
        // A changed signature.
        let mut t = record.clone();
        let mut s = hex::decode(&t.signature).unwrap();
        s[5] ^= 1;
        t.signature = hex::encode(s);
        assert_eq!(replay(&t, pinned), Err(ReplayRefusal::BadSignature));
        // A changed decision.
        let mut t = record.clone();
        t.body.decided.decision = Decision::Fail;
        assert_eq!(replay(&t, pinned), Err(ReplayRefusal::BadSignature));
        // Re-signed by another key.
        let stranger = EvaluatorKey::from_material(&KeyMaterial::from_bytes(seeded(2)));
        let resigned = VerdictRecord::sign(record.body.clone(), &stranger);
        assert_eq!(
            replay(&resigned, pinned),
            Err(ReplayRefusal::OtherEvaluatorKey)
        );

        // The server refuses the tampered and re-signed records, then
        // accepts the genuine one.
        let mut t = record.clone();
        flip_stdout(&mut t);
        let refused = submit(&c, &run, &t).unwrap_err();
        assert_eq!(refused.code, "verdict_refused");
        let text = serde_json::to_string(&resigned).unwrap();
        let refused = c
            .call("verdict", json!({ "run_id": run, "record": text }))
            .unwrap_err();
        assert_eq!(refused.code, "verdict_refused");
        let mut forged = record.clone();
        forged.signature = hex::encode([0u8; 64]);
        let text = serde_json::to_string(&forged).unwrap();
        let refused = c
            .call("verdict", json!({ "run_id": run, "record": text }))
            .unwrap_err();
        assert_eq!(refused.code, "verdict_refused");
        // The genuine record (its observation digests were submitted with
        // the tampered attempt, unchanged) is accepted.
        let text = serde_json::to_string(&record).unwrap();
        let ok = c
            .call("verdict", json!({ "run_id": run, "record": text }))
            .unwrap();
        assert_eq!(ok["decision"].as_str().unwrap(), "pass");
        keep_record("tamper", &record);
        // A record for one run is refused for another; a record whose
        // observations were never submitted is refused; submitted, it is
        // accepted.
        let run2 = fx.evaluator.begin(&c, &req).unwrap();
        let (record2, _world2) = fx.evaluator.prepare(&c, &req, &run2).unwrap();
        let refused = c
            .call("verdict", json!({ "run_id": run2, "record": text }))
            .unwrap_err();
        assert_eq!(refused.code, "verdict_mismatch");
        let text2 = serde_json::to_string(&record2).unwrap();
        let refused = c
            .call("verdict", json!({ "run_id": run2, "record": text2 }))
            .unwrap_err();
        assert_eq!(refused.code, "observations_mismatch");
        let ok = submit(&c, &run2, &record2).unwrap();
        assert_eq!(ok["decision"].as_str().unwrap(), "pass");
        keep_record("tamper-genuine", &record2);
    }

